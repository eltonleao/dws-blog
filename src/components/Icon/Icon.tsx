export type IconName = keyof typeof VECTOR | keyof typeof LEGACY

interface IconProps {
  name: IconName
  /**
   * The width of the box, in px; the height follows. A vector icon with no
   * size takes the box of the vector, a drawn one the 24 of its grid.
   */
  size?: number
  className?: string
}

/**
 * An icon of the design, as inline SVG in the color of the text around it.
 * It is decoration: the control that holds it carries the name.
 */
export function Icon({ name, size, className }: IconProps) {
  if (name in VECTOR) {
    const icon: VectorIcon = VECTOR[name as keyof typeof VECTOR]
    const { width, height, x = 0, y = 0, d } = icon
    const boxWidth = x || y ? Math.ceil(x + width) : width
    const boxHeight = x || y ? Math.ceil(y + height) : height
    const scale = size === undefined ? 1 : size / width
    return (
      <svg
        className={className}
        width={+(boxWidth * scale).toFixed(3)}
        height={+(boxHeight * scale).toFixed(3)}
        viewBox={`${-x} ${-y} ${boxWidth} ${boxHeight}`}
        fill="currentColor"
        aria-hidden="true"
        focusable="false"
      >
        <path d={d} />
      </svg>
    )
  }
  return (
    <svg
      className={className}
      width={size ?? 24}
      height={size ?? 24}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {LEGACY[name as keyof typeof LEGACY]}
    </svg>
  )
}
